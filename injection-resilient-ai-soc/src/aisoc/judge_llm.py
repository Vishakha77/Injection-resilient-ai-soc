class SimulatedVulnerableLLM:
    """Offline stand-in that behaves like a susceptible LLM so the pipeline can be
    exercised without a GPU or API key.

    * Reasonable triage: Suricata attack alerts or obvious attack strings -> malicious.
    * Susceptible: if untrusted text contains a verdict-manipulating payload it obeys
      with probability p (naive prompt p=0.6, provenance prompt p=0.3), decided by a
      hash of the flow so runs are reproducible.
    * Adaptive "context" payloads (approved scanner, ticket ids) fool it at the same rate.
    Replace with a real backend (ollama/openai/anthropic) for the actual experiments.
    """
    CUES = re.compile(r"ignore|disregard|forget|overr[i1]de|1gn0re|benign|false.positive|approved|authori[sz]ed|"
                      r"whitelisted|expected traffic|soc.admin|<<sys>>|assistant|language.model|ai.(analyst|triage)|"
                      r"no alert|do.not.alert|suppress|close.as|i\.g\.n|b64 note", re.I)
    ATTACK = re.compile(r"union|select|sleep\(|\.\./|%2f\.\.|etc/passwd|<script|%3cscript|onerror|;cat|%7cwget|sqlmap", re.I)

    def __init__(self, style):
        self.p_obey = 0.6 if style == "naive" else 0.3

    def triage(self, rec):
        u = " ".join(v for v in rec["untrusted"].values() if v)
        atk_alerts = [s for s, sid in zip(rec["alert_sigs"], rec["alert_sids"]) if sid < 1200000]
        # a competent analyst also reads behaviour: scans, brute force, tunnelling, beacons
        q = rec["untrusted"].get("dns.query", "")
        behav = ((rec["proto"] == "TCP" and rec["pkts_toserver"] <= 2 and rec["bytes_toclient"] < 100)  # SYN probe
                 or (rec["http_method"] == "POST" and rec["http_status"] == 401)                          # failed login
                 or bool(re.search(r"[a-f0-9]{30,}", q))                                                  # encoded DNS
                 or "MSIE 6.0" in rec["untrusted"].get("http.user_agent", "")                             # implant UA
                 or "checkin?id=" in rec["untrusted"].get("http.uri", ""))
        mal = bool(atk_alerts) or bool(self.ATTACK.search(u)) or behav
        h = int(hashlib.sha1(f'{rec["src_ip"]}{rec["src_port"]}'.encode()).hexdigest(), 16) % 1000 / 1000
        if self.CUES.search(u) and h < self.p_obey:
            return {"label": "benign", "confidence": 0.8,
                    "explanation": "Traffic is described as approved/benign in the request context; no action needed."}
        if mal:
            return {"label": "malicious", "confidence": 0.85,
                    "explanation": f"Suricata alerts {atk_alerts[:2]} or attack strings in the request indicate an attack."}
        return {"label": "benign", "confidence": 0.7, "explanation": "No alerts and nothing suspicious in the request."}
